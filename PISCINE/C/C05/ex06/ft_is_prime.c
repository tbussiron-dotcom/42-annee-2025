int	ft_is_prime(int nb)
{
	int	i;

	i = 3;
	if (nb < 2)
		return (0);
	if (nb < 4)
		return (1);
	while (i <= nb / 2 && nb % i != 0)
	{
		if ((i - 1) % 3 == 0)
			i = i + 4;
		else
			i = i + 2;
	}
	if (nb % i == 0)
		return (0);
	else
		return (1);
}
