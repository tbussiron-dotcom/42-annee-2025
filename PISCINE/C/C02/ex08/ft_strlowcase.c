char	*ft_strlowcase(char *src)
{
	int	i;

	i = 0;
	while (src[i] != '\0')
	{
		if (src[i] >= 'A' && src[i] <= 'Z')
			src[i] += 32;
		i++;
	}
	return (src);
}
